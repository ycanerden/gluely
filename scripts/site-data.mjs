// Writes site/data.js from the library, so the page shows what the CLI really offers.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadLibrary, loadPlaybooks } from '../src/library.js';

const site = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'site', 'data.js');

export function siteData() {
  const { jobs, access, tools } = loadLibrary();
  const playbooks = loadPlaybooks().map(({ id, name, summary, steps }) => ({ id, name, summary, steps }));
  return `// Generated by scripts/site-data.mjs. Edit library/ instead.\nwindow.GLUELY = ${JSON.stringify({ jobs, access, tools, playbooks })};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) fs.writeFileSync(site, siteData());
